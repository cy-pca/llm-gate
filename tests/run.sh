#!/usr/bin/env bash
# Self-tests for llm-gate.sh and ci.sh. Every fixture commit lives in a throwaway
# repo under a temp dir; nothing here is ever pushed anywhere.
#
# A few vendor strings are assembled from variables ($C, $c, $AN) so that
# scanners looking for those literals (editor hooks, pre-commit checks) don't
# trip on this file.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
gate=$here/llm-gate.sh
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
unset GITHUB_ACTIONS GITHUB_STEP_SUMMARY

C=Cl; C+=aude      # display name
c=cl; c+=aude      # lowercase, for URLs
AN=anthr; AN+=opic
CO=Co-authored-by
GEN='Generated with'

pass=0 fail=0
ok() { pass=$((pass + 1)); }
bad() { fail=$((fail + 1)); printf 'FAIL: %s\n' "$*"; }

# expect flag|clean MESSAGE
expect() {
  local want=$1 msg=$2 got
  if printf '%s\n' "$msg" | bash "$gate" -q --message-file - >/dev/null 2>&1; then got=clean; else got=flag; fi
  if [[ $got == "$want" ]]; then ok; else bad "expected $want, got $got for: $(printf '%s' "$msg" | tr '\n' '|')"; fi
}

msg() { printf 'Fix the widget\n\nSome body text.\n\n%s\n' "$1"; }

echo '== attribution that must be flagged'
expect flag "$(msg "$CO: $C <noreply@$AN.com>")"
expect flag "$(msg "co-authored-by:$C <noreply@$AN.com>")"
expect flag "$(msg "$CO: $C Opus 4.5 <noreply@$AN.com>")"
expect flag "$(msg "$CO: $C Sonnet 4 <x@example.com>")"
expect flag "$(msg "$CO: $C <some-other@example.com>")"
expect flag "$(msg "$CO: someone <noreply@$AN.com>")"
expect flag "$(msg "$CO: Copilot <198982749+Copilot@users.noreply.github.com>")"
expect flag "$(msg "$CO: copilot-swe-agent[bot] <198982749+Copilot@users.noreply.github.com>")"
expect flag "$(msg "$CO: GitHub Copilot <copilot@github.com>")"
expect flag "$(msg "$CO: chatgpt-codex-connector[bot] <199175422+chatgpt-codex-connector[bot]@users.noreply.github.com>")"
expect flag "$(msg "$CO: Cursor Agent <cursoragent@cursor.com>")"
expect flag "$(msg "$CO: aider (openai/gpt-4o) <noreply@aider.chat>")"
expect flag "$(msg "$CO: Amp <amp@ampcode.com>")"
expect flag "$(msg "$CO: Crush <crush@charm.land>")"
expect flag "$(msg "$CO: Warp <agent@warp.dev>")"
expect flag "$(msg "$CO: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>")"
expect flag "$(msg "$CO: google-labs-jules[bot] <161369871+google-labs-jules[bot]@users.noreply.github.com>")"
expect flag "$(msg "$CO: Gemini <gemini@example.com>")"
expect flag "$(msg "$CO: factory-droid[bot] <138933559+factory-droid[bot]@users.noreply.github.com>")"
expect flag "$(msg "$CO: amazon-q-developer[bot] <1+amazon-q-developer[bot]@users.noreply.github.com>")"
expect flag "$(msg "$CO: ChatGPT <noreply@openai.com>")"
expect flag "$(msg "Signed-off-by: $C <noreply@$AN.com>")"
expect flag "$(msg "Assisted-by: $C:$c-opus-4 coccinelle")"
expect flag "$(msg "Assisted-by: GPT-5 via Copilot")"
expect flag "$(msg "Generated-by: Gemini CLI")"
expect flag "$(msg "AI-Assisted: yes")"
expect flag "$(msg "Amp-Thread-ID: https://ampcode.com/threads/T-1234")"
expect flag "$(msg "$C-Session: abc123")"
expect flag "$(msg "🤖 $GEN [$C Code](https://$c.com/$c-code)")"
expect flag "$(msg "$GEN [$C Code](https://$c.com/$c-code)")"
expect flag "$(msg "💘 $GEN Crush")"
expect flag "$(msg "Generated by ChatGPT")"
expect flag "$(msg "Co-written with GitHub Copilot.")"
expect flag "$(msg "Written with Cursor")"
expect flag "$(msg "Created with the help of an AI assistant")"
expect flag "$(msg "With help from Gemini 2.5 Pro")"
expect flag "$(msg "This PR was generated with $C Code.")"
expect flag "$(msg "This change was partially generated by Codex")"
expect flag "$(msg "https://$c.ai/code/session_01ABCdef")"
expect flag "$(msg "Codex task: https://chatgpt.com/codex/tasks/task_e_123")"
expect flag "$(msg "See https://app.devin.ai/sessions/abc for the transcript")"
expect flag "$(printf '%s\r\n\r\n%s\r\n' 'CRLF message' "$CO: $C <noreply@$AN.com>")"
expect flag "$GEN Copilot: add widget"

echo '== ordinary messages that must pass'
expect clean "$(msg "$CO: $C Monet <claude.monet@example.com>")"
expect clean "$(msg "$CO: Devin Lee <devin@example.com>")"
expect clean "$(msg "$CO: Jules Verne <jules@example.com>")"
expect clean "$(msg "$CO: Cody Smith <cody@example.com>")"
expect clean "$(msg "$CO: Jane Doe <jane@cursor.com>")"
expect clean "$(msg "$CO: Kiro Tanaka <kiro@example.jp>")"
expect clean "$(msg "Signed-off-by: Joe Rivera <j@jriv.us>")"
expect clean "$(msg "Reviewed-by: Ann Example <ann@example.com>")"
expect clean "$(msg "Assisted-by: Jane Doe <jane@example.com>")"
expect clean "$(msg "Generated by protoc-gen-go. DO NOT EDIT.")"
expect clean "$(msg "Generated with mockery v2")"
expect clean "$(msg "Made with love in Austin")"
expect clean "$(msg "Fix cursor position after paste")"
expect clean "$(msg "Add an OpenAI client wrapper for the summarizer")"
expect clean "$(msg "Bump llama.cpp to b4500")"
expect clean "$(msg "The parser now handles files generated by older tools.")"
expect clean "$(msg "Dependabot: bump actions/checkout from 4 to 5")"
expect clean "$(msg "$CO: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>")"
expect clean "$(msg "$CO: mend-bolt-for-github[bot] <42819689+mend-bolt-for-github[bot]@users.noreply.github.com>")"
expect clean "$(msg "Docs: link the $C API reference at https://docs.$AN.com")"
expect clean "ai-tools: add model registry"
expect clean "llm-client: retry on 529"
expect clean "Copilot-chat: fix keybinding"

echo '== --message-file strips git comments and the -v diff'
printf 'Fix widget\n\n# Please enter the commit message\n# ------------------------ >8 ------------------------\n+%s: %s <noreply@%s.com>\n' "$CO" "$C" "$AN" >"$tmp/COMMIT_EDITMSG"
if bash "$gate" -q --message-file "$tmp/COMMIT_EDITMSG" >/dev/null 2>&1; then ok; else bad 'commit -v diff below scissors was checked'; fi
printf 'Fix widget\n\n%s: %s <noreply@%s.com>\n' "$CO" "$C" "$AN" >"$tmp/COMMIT_EDITMSG"
if bash "$gate" -q --message-file "$tmp/COMMIT_EDITMSG" >/dev/null 2>&1; then bad 'hook file with trailer passed'; else ok; fi

echo '== --ignore-patterns and --extra-patterns'
printf '# people, not tools\n^%s: %s <claude@example\\.org>$\n' "$CO" "$C" >"$tmp/ignore"
if printf 'x\n\n%s: %s <claude@example.org>\n' "$CO" "$C" | bash "$gate" -q --ignore-patterns "$tmp/ignore" --message-file - >/dev/null 2>&1; then ok; else bad 'ignore pattern not applied'; fi
printf 'x-tool-session:\n' >"$tmp/extra"
if printf 'x\n\nX-Tool-Session: 42\n' | bash "$gate" -q --extra-patterns "$tmp/extra" --message-file - >/dev/null 2>&1; then bad 'extra pattern not applied'; else ok; fi

echo '== --filter'
in=$(printf 'Fix the widget\n\nBody line.\n\n🤖 %s [%s Code](https://%s.com/%s-code)\n\n%s: %s <noreply@%s.com>\nSigned-off-by: Joe Rivera <j@jriv.us>\n' "$GEN" "$C" "$c" "$c" "$CO" "$C" "$AN")
want=$(printf 'Fix the widget\n\nBody line.\n\nSigned-off-by: Joe Rivera <j@jriv.us>')
got=$(printf '%s\n' "$in" | bash "$gate" --filter)
if [[ $got == "$want" ]]; then ok; else bad "filter output:"$'\n'"$got"; fi
in=$(printf 'Fix the widget\n\nBody line.\n\n%s: %s <noreply@%s.com>\n' "$CO" "$C" "$AN")
got=$(printf '%s\n' "$in" | bash "$gate" --filter)
if [[ $got == $'Fix the widget\n\nBody line.' ]]; then ok; else bad "filter left trailing blanks: $(printf '%q' "$got")"; fi

# ---------------------------------------------------------------------------
echo '== revision ranges'
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null
export GIT_AUTHOR_NAME='Dev Person' GIT_AUTHOR_EMAIL=dev@example.com
export GIT_COMMITTER_NAME='Dev Person' GIT_COMMITTER_EMAIL=dev@example.com
repo=$tmp/repo
git init -q -b main "$repo"
cd "$repo"
commit() { git commit -q --allow-empty -m "$1" "${@:2}"; }
commit 'initial'
git checkout -q -b clean
commit 'Add feature'
commit $'Fix bug\n\nSigned-off-by: Dev Person <dev@example.com>'
git checkout -q -b dirty
commit $'Refactor\n\n'"$CO: $C <noreply@$AN.com>"
git checkout -q -b bot-author clean
GIT_AUTHOR_NAME='copilot-swe-agent[bot]' GIT_AUTHOR_EMAIL='198982749+Copilot@users.noreply.github.com' commit 'Initial plan'

if bash "$gate" -q main..clean >/dev/null 2>&1; then ok; else bad 'clean branch flagged'; fi
if out=$(bash "$gate" -q main..dirty 2>&1); then bad 'trailer branch passed'; else ok; fi
if [[ $out == *'AI co-author trailer'* ]]; then ok; else bad "missing rule name in: $out"; fi
if bash "$gate" -q main..bot-author >/dev/null 2>&1; then bad 'bot author passed'; else ok; fi
if bash "$gate" -q --no-identities main..bot-author >/dev/null 2>&1; then ok; else bad '--no-identities still flagged author'; fi
bash "$gate" -q main..no-such-branch >/dev/null 2>&1 && st=0 || st=$?
if [[ $st == 2 ]]; then ok; else bad "bad range exit $st, want 2"; fi

echo '== GitHub Actions output'
export GITHUB_ACTIONS=true GITHUB_STEP_SUMMARY=$tmp/summary
out=$(bash "$gate" main..dirty 2>&1) || true
if [[ $out == *'::error title=llm-gate%3A AI co-author trailer in '* ]]; then ok; else bad "no annotation in: $out"; fi
if grep -q '&lt;noreply@' "$GITHUB_STEP_SUMMARY"; then ok; else bad "summary not escaped: $(cat "$GITHUB_STEP_SUMMARY")"; fi
unset GITHUB_ACTIONS GITHUB_STEP_SUMMARY

# ---------------------------------------------------------------------------
echo '== ci.sh against a file:// "GitHub"'
# Serve the fixture repo the way GitHub does: partial clone and fetch-by-SHA allowed.
server=$tmp/server
server_url=file://$server
command -v cygpath >/dev/null && server_url=file:///$(cygpath -m "$server") # Git for Windows
mkdir -p "$server/org"
git clone -q --bare "$repo" "$server/org/repo.git"
git -C "$server/org/repo.git" config uploadpack.allowFilter true
git -C "$server/org/repo.git" config uploadpack.allowAnySHA1InWant true
sha() { git -C "$repo" rev-parse "$1"; }

# run_ci WANT_STATUS DESCRIPTION [VAR=VALUE...]
run_ci() {
  local want=$1 what=$2 st
  shift 2
  (
    cd "$tmp" # not a checkout: forces the fetch path
    export GITHUB_SERVER_URL="$server_url" GITHUB_REPOSITORY=org/repo RUNNER_TEMP=$tmp/runner
    export GITHUB_WORKSPACE=$tmp/empty-workspace LLM_GATE_CHECK_IDENTITIES=true LLM_GATE_CHECK_PR_TEXT=true
    export LLM_GATE_DEFAULT_BRANCH=main LLM_GATE_TOKEN=
    mkdir -p "$RUNNER_TEMP" "$GITHUB_WORKSPACE"
    for kv in "$@"; do export "${kv?}"; done
    bash "$here/ci.sh"
  ) >"$tmp/ci.out" 2>&1 && st=0 || st=$?
  if [[ $st == "$want" ]]; then ok; else bad "ci.sh $what: exit $st, want $want"; sed 's/^/    /' "$tmp/ci.out"; fi
}

run_ci 0 'clean PR' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha clean)" LLM_GATE_PR_TITLE='Add feature'
run_ci 1 'PR with trailer' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha dirty)"
run_ci 1 'PR with bot author' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha bot-author)"
run_ci 0 'bot author, identities off' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha bot-author)" LLM_GATE_CHECK_IDENTITIES=false
run_ci 1 'PR body footer' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha clean)" LLM_GATE_PR_TITLE='Add feature' \
  LLM_GATE_PR_BODY="$(printf 'Summary\n\n🤖 %s [%s Code](https://%s.com/%s-code)' "$GEN" "$C" "$c" "$c")"
run_ci 0 'PR body footer, PR text off' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha clean)" LLM_GATE_CHECK_PR_TEXT=false \
  LLM_GATE_PR_BODY="$GEN Copilot"
run_ci 1 'new-branch push (zero before)' LLM_GATE_BASE=0000000000000000000000000000000000000000 LLM_GATE_HEAD="$(sha dirty)"
run_ci 0 'branch delete push (zero after)' LLM_GATE_BASE="$(sha dirty)" LLM_GATE_HEAD=0000000000000000000000000000000000000000
run_ci 1 'ignore patterns from input' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha dirty)" LLM_GATE_IGNORE_PATTERNS='^nothing-matches$'
run_ci 0 'ignore patterns from input' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha dirty)" \
  LLM_GATE_IGNORE_PATTERNS="$(printf '# exempt\n^%s: ' "$CO")"
run_ci 2 'unknown head' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD=1111111111111111111111111111111111111111

# A full, non-shallow checkout that already has both commits is used in place.
run_ci 1 'workspace checkout' LLM_GATE_BASE="$(sha main)" LLM_GATE_HEAD="$(sha dirty)" GITHUB_WORKSPACE="$repo" \
  GITHUB_SERVER_URL=file:///nonexistent
if grep -q 'using the checkout' "$tmp/ci.out"; then ok; else bad "workspace checkout not used: $(cat "$tmp/ci.out")"; fi

echo
printf '%d passed, %d failed\n' "$pass" "$fail"
((fail == 0))
